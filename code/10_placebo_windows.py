"""Step 10: placebo windows. How often does R1 look "significant" when there is no bank run? (specs_tried.md #28)

HC3 standard errors treat banks as independent, but all banks share the same three trading days, so their
returns are correlated (README threat 10). Here R1 is rerun on every three-day window of 2022, with the same
Dec 2022 predictors. In those windows there was no run, so the share of "significant" results is the real
false-positive rate of R1's test, and R1's March t-statistic can be ranked against them.

Each placebo BHAR is computed exactly like bhar_0_2 in step 3 (same total-return function), over days t to t+2.

Inputs:  data/raw/crsp/*.csv (licensed), outputs/final_dataset.csv, outputs/regressions.csv
Outputs: outputs/placebo_windows.csv   one row per placebo window (regression results only, no CRSP rows)
         outputs/placebo_windows.md    the summary in specs_tried.md #28's terms
"""
import importlib

import numpy as np
import pandas as pd
import statsmodels.formula.api as smf

from config import OUTPUTS

crsp_returns = importlib.import_module("03_crsp_returns")   # reuse step 3's loader and total-return rule

FORMULA = "bhar ~ uninsured_dep_share + htm_loss_to_equity + log_assets"   # R1's right-hand side
R1_SPEC_PREFIX = "R1 "
PLACEBO_YEAR = 2022
WINDOW_DAYS = 3
VAR = "uninsured_dep_share"


def placebo_bhars(d, m, permnos):
    """BHAR over days t..t+2 for every 2022 trading day t whose window stays in 2022. Rows: day 0; columns: PERMNO."""
    cal = m.loc[m["date"].dt.year == PLACEBO_YEAR, "date"].sort_values().reset_index(drop=True)
    mkt = m.set_index("date")["vwretd"]
    r = (d[d["permno"].isin(permnos) & d["date"].isin(cal)]
         .pivot(index="date", columns="permno", values="r").reindex(cal))
    out = {}
    for i in range(len(cal) - WINDOW_DAYS + 1):
        days = cal.iloc[i: i + WINDOW_DAYS]
        g = r.loc[days]
        bhr = (1 + g).prod(min_count=WINDOW_DAYS) - 1
        bhr[g.isna().any()] = np.nan                     # need a return on all three days
        out[days.iloc[0]] = bhr - ((1 + mkt[days]).prod() - 1)
    return pd.DataFrame(out).T


def main():
    d, m = crsp_returns.load()
    d = crsp_returns.total_return(d)

    df = pd.read_csv(OUTPUTS / "final_dataset.csv")
    main_sample = df[df["main_sample"]].copy()
    main_sample["permno"] = main_sample["permno"].astype(int)
    bhars = placebo_bhars(d, m, set(main_sample["permno"]))

    rows = []
    for day0, bhar in bhars.iterrows():
        data = main_sample.assign(bhar=main_sample["permno"].map(bhar)).dropna(subset=["bhar"])
        fit = smf.ols(FORMULA, data=data).fit(cov_type="HC3")
        rows.append({"day0": day0.date(), "n": int(fit.nobs), "coef": fit.params[VAR], "se": fit.bse[VAR],
                     "t": fit.tvalues[VAR], "p": fit.pvalues[VAR], "mean_bhar": data["bhar"].mean()})
    res = pd.DataFrame(rows)
    res["non_overlapping"] = res.index % WINDOW_DAYS == 0      # every third window, starting Jan 3
    res.to_csv(OUTPUTS / "placebo_windows.csv", index=False, float_format="%.6g")

    reg = pd.read_csv(OUTPUTS / "regressions.csv")
    r1 = reg[reg["spec"].str.startswith(R1_SPEC_PREFIX) & (reg["variable"] == VAR)].iloc[0]

    def summary(sub):
        return {"windows": len(sub),
                "false_pos": (sub["p"] < 0.05).mean(),
                "placebo_p": (sub["t"].abs() >= abs(r1.t)).mean(),
                "coef_le": (sub["coef"] <= r1.coef).mean()}

    s_all, s_non = summary(res), summary(res[res["non_overlapping"]])
    lines = ["# Placebo windows", "",
             "Generated by `code/10_placebo_windows.py` (`specs_tried.md` #28). R1 (BHAR over days 0 to +2 on uninsured share, "
             "HTM loss / equity and log assets, HC3) rerun on every three-day window of 2022, with the same Dec 2022 "
             "predictors and the main sample. There was no bank run in these windows, so a \"significant\" uninsured-share "
             "coefficient there is a false positive.", "",
             f"March 2023 (R1): coefficient {r1.coef:.3f}, t = {r1.t:.2f}, HC3 p = {r1.p:.3f}, N = {int(r1.n)}.", "",
             "| | All windows | Non-overlapping |", "|---|---|---|",
             f"| Placebo windows | {s_all['windows']} | {s_non['windows']} |",
             f"| Banks per window | {res['n'].min()}–{res['n'].max()} | "
             f"{res.loc[res['non_overlapping'], 'n'].min()}–{res.loc[res['non_overlapping'], 'n'].max()} |",
             f"| (a) Share with HC3 p < 0.05 (nominal 5%) | {s_all['false_pos']:.1%} | {s_non['false_pos']:.1%} |",
             f"| (b) Placebo p-value for March: share with \\|t\\| ≥ {abs(r1.t):.2f} | {s_all['placebo_p']:.3f} | {s_non['placebo_p']:.3f} |",
             f"| (c) Share with coefficient ≤ {r1.coef:.3f} | {s_all['coef_le']:.3f} | {s_non['coef_le']:.3f} |",
             "",
             f"Placebo coefficients: median {res['coef'].median():.3f}, 5th–95th percentile "
             f"{res['coef'].quantile(.05):.3f} to {res['coef'].quantile(.95):.3f}. "
             f"Placebo t-statistics: 5th–95th percentile {res['t'].quantile(.05):.2f} to {res['t'].quantile(.95):.2f} "
             "(about −1.65 to 1.65 if HC3 were right).", ""]
    (OUTPUTS / "placebo_windows.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
