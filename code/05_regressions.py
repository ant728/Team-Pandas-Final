"""Step 5: first cross-sectional regressions (v0). Did more fragile banks fall more around SVB?

Every specification run here is also logged in specs_tried.md. Standard errors are heteroskedasticity-robust (HC3).

Outputs:
  outputs/summary_stats.csv     descriptive statistics for the in-sample banks
  outputs/regressions_v0.csv    one row per specification x variable
  outputs/regressions_v0.md     the same, as a readable table
"""
import pandas as pd
import statsmodels.formula.api as smf

from config import OUTPUTS

SPECS = {
    "R1 BHAR on uninsured share + HTM loss/equity": ("bhar_0_2 ~ uninsured_dep_share + htm_loss_to_equity + log_assets", "all"),
    "R2 BHAR on uninsured share + all securities loss/equity": ("bhar_0_2 ~ uninsured_dep_share + sec_loss_to_equity + log_assets", "all"),
    "R3 R1 without SVB and Signature (imputed -100%)": ("bhar_0_2 ~ uninsured_dep_share + htm_loss_to_equity + log_assets", "no_imputed"),
    "R4 R1 with market-model CAR as the outcome": ("car_0_2 ~ uninsured_dep_share + htm_loss_to_equity + log_assets", "all"),
}


def main():
    df = pd.read_csv(OUTPUTS / "final_dataset.csv")
    df = df[df["in_sample"]]

    stats = df[["total_assets_bn", "uninsured_dep_share", "htm_loss_to_equity", "sec_loss_to_equity",
                "bhr_0_2", "bhar_0_2", "car_0_2"]].describe(percentiles=[.1, .5, .9]).T
    stats.to_csv(OUTPUTS / "summary_stats.csv", float_format="%.4f")

    rows = []
    for name, (formula, sample) in SPECS.items():
        data = df if sample == "all" else df[~df["dlret_imputed"].astype(bool)]
        fit = smf.ols(formula, data=data).fit(cov_type="HC3")
        for var in fit.params.index:
            rows.append({"spec": name, "formula": formula, "variable": var, "coef": fit.params[var],
                         "se": fit.bse[var], "t": fit.tvalues[var], "p": fit.pvalues[var],
                         "n": int(fit.nobs), "r2": fit.rsquared})
    res = pd.DataFrame(rows)
    res.to_csv(OUTPUTS / "regressions_v0.csv", index=False, float_format="%.6g")

    lines = ["# v0 regressions", "",
             "Generated by `code/05_regressions.py`. Outcome: buy-and-hold abnormal return over Mar 9-13, 2023 "
             "(R4: market-model CAR). Robust (HC3) standard errors. Every spec is logged in `specs_tried.md`.", ""]
    for name, g in res.groupby("spec", sort=False):
        lines += [f"## {name}", f"N = {g['n'].iloc[0]}, R-squared = {g['r2'].iloc[0]:.3f}", "",
                  "| Variable | Coef | SE | t | p |", "|---|---|---|---|---|"]
        lines += [f"| {r.variable} | {r.coef:.4f} | {r.se:.4f} | {r.t:.2f} | {r.p:.3f} |" for r in g.itertuples()]
        lines.append("")
    (OUTPUTS / "regressions_v0.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
