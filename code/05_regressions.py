"""Step 5: cross-sectional regressions. Did more fragile banks fall more around SVB?

Every specification run here is also logged in specs_tried.md. Standard errors are heteroskedasticity-robust (HC3).

Outputs:
  outputs/summary_stats.csv     descriptive statistics for the in-sample banks
  outputs/regressions.csv    one row per specification x variable
  outputs/regressions.md     the same, as a readable table
"""
import pandas as pd
import statsmodels.formula.api as smf

from config import OUTPUTS

# Samples (specs_tried.md #17, instructor audit A2):
#   main          in_sample without SVB, the bank that triggered the event (Signature stays in, at -100%)
#   with_trigger  all in_sample banks, SVB included (the earlier baseline)
#   no_imputed    main without Signature too, so no bank with an imputed -100% delisting return
BASE = "bhar_0_2 ~ uninsured_dep_share + htm_loss_to_equity + log_assets"
SPECS = {
    "R1 BHAR on uninsured share + HTM loss/equity (main sample: without SVB)": (BASE, "main"),
    "R2 BHAR on uninsured share + all securities loss/equity": ("bhar_0_2 ~ uninsured_dep_share + sec_loss_to_equity + log_assets", "main"),
    "R3 R1 also without Signature (no imputed -100% returns)": (BASE, "no_imputed"),
    "R4 R1 with market-model CAR as the outcome": ("car_0_2 ~ uninsured_dep_share + htm_loss_to_equity + log_assets", "main"),
    # Instructor audit A3 (specs_tried.md #14): control for each bank's exposure to the common regional-bank shock.
    "R5 R1 plus beta to KRE (regional-bank ETF)": (BASE + " + kre_beta", "main"),
    "R6 R1 including SVB (the earlier baseline)": (BASE, "with_trigger"),
    # specs_tried.md #18: window that ends before the Mar 12 rescue (days 0 to +1).
    "R7 R1 over Mar 9-10 only (before the rescue)": ("bhar_0_1 ~ uninsured_dep_share + htm_loss_to_equity + log_assets", "main"),
    # specs_tried.md #19: ratios winsorized at the 1st/99th percentiles of the main sample.
    "R8 R1 with winsorized ratios (1st/99th pct)": ("bhar_0_2 ~ uninsured_dep_share_w + htm_loss_to_equity_w + log_assets", "main_w"),
    "R9 R2 with winsorized ratios (1st/99th pct)": ("bhar_0_2 ~ uninsured_dep_share_w + sec_loss_to_equity_w + log_assets", "main_w"),
    # specs_tried.md #20: drop entities whose banks are a small part of the company.
    "R10 R1 on bank-centric companies only": (BASE, "bank_centric"),
}
MAGNITUDE_SPECS = ("R1", "R3", "R6", "R10")   # same-outcome specs on unwinsorized uninsured share
WINSOR_COLS = ["uninsured_dep_share", "htm_loss_to_equity", "sec_loss_to_equity"]
WINSOR_PCT = (0.01, 0.99)


def winsorize(df):
    """Add <col>_w copies clipped at the 1st/99th percentiles of this sample (specs_tried.md #19)."""
    out = df.copy()
    for col in WINSOR_COLS:
        lo, hi = df[col].quantile(list(WINSOR_PCT))
        out[col + "_w"] = df[col].clip(lo, hi)
        print(f"winsorized {col} to [{lo:.3f}, {hi:.3f}]: {(df[col] < lo).sum()} below, {(df[col] > hi).sum()} above")
    return out


def main():
    df = pd.read_csv(OUTPUTS / "final_dataset.csv")
    df = df[df["in_sample"]]
    samples = {"main": df[df["main_sample"]],
               "with_trigger": df,
               "no_imputed": df[df["main_sample"] & ~df["dlret_imputed"].astype(bool)]}
    samples["main_w"] = winsorize(samples["main"])
    samples["bank_centric"] = df[df["bank_centric"]]

    stats = samples["main"][["total_assets_bn", "uninsured_dep_share", "htm_loss_to_equity", "sec_loss_to_equity",
                "bhr_0_2", "bhar_0_2", "car_0_2"]].describe(percentiles=[.1, .5, .9]).T
    stats.to_csv(OUTPUTS / "summary_stats.csv", float_format="%.4f")

    rows = []
    for name, (formula, sample) in SPECS.items():
        fit = smf.ols(formula, data=samples[sample]).fit(cov_type="HC3")
        for var in fit.params.index:
            rows.append({"spec": name, "formula": formula, "variable": var, "coef": fit.params[var],
                         "se": fit.bse[var], "t": fit.tvalues[var], "p": fit.pvalues[var],
                         "n": int(fit.nobs), "r2": fit.rsquared})
    res = pd.DataFrame(rows)
    res.to_csv(OUTPUTS / "regressions.csv", index=False, float_format="%.6g")

    lines = ["# Regressions", "",
             "Generated by `code/05_regressions.py`. Outcome: buy-and-hold abnormal return over Mar 9-13, 2023 "
             "(R4: market-model CAR; R7: Mar 9-10 only). Main sample: every in-sample bank except SVB, the bank that triggered the event "
             "(`specs_tried.md` #17). R3 also drops Signature; R6 puts SVB back. R5 adds each bank's pre-event beta to KRE. R8-R9 winsorize the ratios at the 1st/99th percentiles. R10 keeps bank-centric companies only. "
             "Robust (HC3) standard errors. Every spec is logged in `specs_tried.md`.", ""]
    # Economic size of the main coefficient: effect of a one-standard-deviation higher uninsured share,
    # using the SD of each spec's own estimation sample (self-audit finding I).
    main = samples["main"]
    for spec in [s for s in SPECS if s.split()[0] in MAGNITUDE_SPECS]:
        formula, sample = SPECS[spec]
        sd = samples[sample]["uninsured_dep_share"].std()
        c = res[(res["spec"] == spec) & (res["variable"] == "uninsured_dep_share")].iloc[0]
        lines.append(f"- **Magnitude, {spec.split()[0]}:** a one-SD higher uninsured share ({sd:.1%} of domestic deposits, "
                     f"SD in this spec's own sample of {int(c.n)}) goes with a {c.coef * sd:+.1%} BHAR over the three days "
                     f"(coefficient {c.coef:.3f}, p = {c.p:.3f}).")
    lines += [f"- The average main-sample bank's BHAR was {main['bhar_0_2'].mean():.1%} (median {main['bhar_0_2'].median():.1%}).", ""]
    for name, g in res.groupby("spec", sort=False):
        lines += [f"## {name}", f"N = {g['n'].iloc[0]}, R-squared = {g['r2'].iloc[0]:.3f}", "",
                  "| Variable | Coef | SE | t | p |", "|---|---|---|---|---|"]
        lines += [f"| {r.variable} | {r.coef:.4f} | {r.se:.4f} | {r.t:.2f} | {r.p:.3f} |" for r in g.itertuples()]
        lines.append("")
    (OUTPUTS / "regressions.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
