"""Step 4: recompute numbers from each pipeline step independently and compare.

Checks against outside sources use published figures for SVB (see the notes on each check).
Writes outputs/hand_checks.md and raises if any check fails.
"""
import csv

import pandas as pd

from config import CALL_REPORT_DATE, ESTIMATION_WINDOW, EVENT_DAY0, MARKET, OUTPUTS, RAW

final = pd.read_csv(OUTPUTS / "poc_final_rows.csv").set_index("ticker")
results = []


def check(name, ours, theirs, tol, source):
    ok = abs(ours - theirs) <= tol
    results.append((name, ours, theirs, tol, "PASS" if ok else "FAIL", source))


# --- Step 1/3: call report measures vs. published SVB figures -------------------------------
check("SVB uninsured share of domestic deposits", final.at["SIVB", "uninsured_dep_share"], 0.94, 0.01,
      "Fed's Review of the Supervision and Regulation of SVB (Apr 2023): about 94% of domestic deposits uninsured at end-2022")
check("SVB HTM unrealized loss ($B)", final.at["SIVB", "htm_unrealized_loss_bn"], 15.1, 0.3,
      "SVB Financial Group 2022 10-K: HTM fair value about $15.1B below amortized cost (holding-company level)")

# --- Step 3: aggregation across a holding company's banks, recomputed with a plain loop -------
with open(RAW / f"fdic_financials_{CALL_REPORT_DATE}.csv", newline="") as f:
    jpm_assets = sum(float(r["ASSET"]) for r in csv.DictReader(f) if r["ticker"] == "JPM") / 1e6
# Tolerance 1e-3 because outputs/poc_final_rows.csv is written to 4 decimals.
check("JPM total assets ($B), summed by hand", final.at["JPM", "total_assets_bn"], jpm_assets, 1e-3,
      "raw FDIC rows for JPMorgan's banks")

# --- Step 2/3: WAL's CAR recomputed from raw closing prices --------------------------------------
px = pd.read_csv(RAW / "prices.csv", parse_dates=["date"])
wal = px[px["symbol"] == "WAL"].set_index("date")["close"]
spy = px[px["symbol"] == MARKET].set_index("date")["close"]
dates = list(spy.index)
i0 = dates.index(pd.Timestamp(EVENT_DAY0))
evt = dates[i0: i0 + 3]
prev = dates[i0 - 1]

# Market-adjusted: sum over event days of (stock return - market return), from prices directly.
mktadj = 0.0
last = prev
for d in evt:
    mktadj += (wal[d] / wal[last] - 1) - (spy[d] / spy[last] - 1)
    last = d
check("WAL market-adjusted CAR[0,+2], from prices", final.at["WAL", "car_0_2_mktadj"], mktadj, 1e-4,
      "raw yfinance closes")

# Market model: beta = cov(r, rm) / var(rm) on the estimation window, then sum the ARs.
r = wal.pct_change()
rm = spy.pct_change()
est = dates[i0 + ESTIMATION_WINDOW[0]: i0 + ESTIMATION_WINDOW[1] + 1]
beta = r[est].cov(rm[est]) / rm[est].var()
alpha = r[est].mean() - beta * rm[est].mean()
car = sum(r[d] - (alpha + beta * rm[d]) for d in evt)
check("WAL market-model CAR[0,+2], cov/var formula", final.at["WAL", "car_0_2"], car, 1e-4,
      "raw yfinance closes")

# --- Write report --------------------------------------------------------------------------------
lines = ["# Hand checks", "",
         "Generated by `code/04_hand_checks.py`. Each number from the pipeline is recomputed another way.", "",
         "| Check | Pipeline | Independent | Tolerance | Result | Source of independent number |",
         "|---|---|---|---|---|---|"]
for name, ours, theirs, tol, res, src in results:
    lines.append(f"| {name} | {ours:.4f} | {theirs:.4f} | {tol:g} | {res} | {src} |")
(OUTPUTS / "hand_checks.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("\n".join(lines))

failed = [r[0] for r in results if r[4] == "FAIL"]
assert not failed, f"hand checks failed: {failed}"
