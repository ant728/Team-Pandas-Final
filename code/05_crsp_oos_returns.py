"""Build 2023 out-of-sample buy-and-hold outcomes from local CRSP files.

CRSP is licensed data. The raw inputs belong in ignored ``data/raw/`` and must
not be committed. This script writes only a per-security holding-period return
summary; it never copies daily CRSP rows to outputs.

Return window: 2023-03-13 close through 2023-12-29 close. Daily CRSP RET is
compounded; on the CRSP delisting date, RET and DLRET are combined as
(1 + RET) * (1 + DLRET) - 1. CRSP delisting code 584 with missing DLRET is
assigned -100%, per the pre-specified conservative failure convention.
"""
from pathlib import Path

import numpy as np
import pandas as pd

from config import OUTPUTS, PROCESSED, RAW

START = pd.Timestamp("2023-03-13")
END = pd.Timestamp("2023-12-29")
DAILY = RAW / "crsp_daily_2022_2023.csv"
MARKET = RAW / "crsp_market_vwretd.csv"
PERMCOS = RAW / "crsp_permcos.csv"
OUT = PROCESSED / "crsp_oos_return_summary.csv"
REPORT = OUTPUTS / "crsp_oos_outcome_summary.md"


def holding_period_return(g: pd.DataFrame, market_dates: pd.DatetimeIndex) -> dict:
    g = g.sort_values("date")
    before = g[g["date"] <= START]
    if before.empty or before.iloc[-1]["date"] != START:
        return {"oos_bhar": np.nan, "oos_status": "missing_2023_03_13_base"}

    period = g[(g["date"] > START) & (g["date"] <= END)].copy()
    if period.empty:
        return {"oos_bhar": np.nan, "oos_status": "no_post_start_observations"}
    if period["date"].duplicated().any():
        raise ValueError(f"duplicate PERMNO-date rows for {g.iloc[0]['permno']}")

    delisted = period["dlstdt"].notna() & (period["date"] == period["dlstdt"])
    if delisted.any():
        end_date = period.loc[delisted, "date"].iloc[-1]
        period = period[period["date"] <= end_date].copy()
    else:
        end_date = END
        if period["date"].max() < END:
            return {"oos_bhar": np.nan, "oos_status": "series_ends_before_horizon_without_delisting"}

    expected = market_dates[(market_dates > START) & (market_dates <= end_date)]
    actual = pd.DatetimeIndex(period["date"])
    if not expected.equals(actual):
        return {"oos_bhar": np.nan, "oos_status": "incomplete_trading_day_coverage"}
    if period["ret"].isna().any():
        return {"oos_bhar": np.nan, "oos_status": "missing_daily_ret"}

    daily_ret = period["ret"].astype(float).to_numpy(copy=True)
    status = "observed_through_2023_12_29" if end_date == END else "delisting_return_included"
    for idx, row in enumerate(period.itertuples(index=False)):
        if pd.notna(row.dlret):
            daily_ret[idx] = (1 + daily_ret[idx]) * (1 + float(row.dlret)) - 1
        elif pd.notna(row.dlstcd) and int(row.dlstcd) == 584:
            daily_ret[idx] = -1.0
            status = "failure_missing_dlret_assumed_total_loss"
        elif pd.notna(row.dlstcd) and row.date == row.dlstdt:
            return {"oos_bhar": np.nan, "oos_status": f"missing_dlret_code_{int(row.dlstcd)}"}

    return {"oos_bhar": float(np.prod(1 + daily_ret) - 1), "oos_status": status}


def main() -> None:
    daily = pd.read_csv(DAILY, parse_dates=["date", "dlstdt"])
    market = pd.read_csv(MARKET, parse_dates=["date"])
    permcos = pd.read_csv(PERMCOS)
    if daily.duplicated(["permno", "date"]).any():
        raise ValueError("CRSP daily input has duplicate PERMNO-date rows")
    if permcos["permco"].duplicated().any():
        raise ValueError("CRSP PERMCO crosswalk is not unique")

    market_dates = pd.DatetimeIndex(market.loc[market["date"].between(START, END), "date"])
    if START not in set(daily["date"]) or END not in set(market_dates):
        raise ValueError("CRSP inputs do not cover the required start/end dates")

    records = []
    for permno, group in daily.groupby("permno", sort=False):
        base = group.sort_values("date").iloc[0]
        if group["permco"].nunique() != 1:
            raise ValueError(f"PERMNO {permno} maps to multiple PERMCOs")
        outcome = holding_period_return(group, market_dates)
        records.append({"permno": int(permno), "permco": int(base["permco"]),
                        "ticker": base["ticker"], "comnam": base["comnam"], **outcome})

    results = pd.DataFrame(records).merge(permcos[["permco", "rssd_id"]], on="permco", how="left", validate="1:1")
    if results["permco"].nunique() != 343:
        raise ValueError(f"Expected 343 PERMCOs; got {results['permco'].nunique()}")
    PROCESSED.mkdir(parents=True, exist_ok=True)
    results.sort_values("permco").to_csv(OUT, index=False, float_format="%.6f")

    observed = results[results["oos_bhar"].notna()]
    severe = observed[observed["oos_bhar"] <= -0.50]
    named = results[results["ticker"].isin(["FRC", "PACW", "SIVB", "SBNY"])]
    lines = [
        "# CRSP out-of-sample return outcomes",
        "",
        "Generated by `code/05_crsp_oos_returns.py` from local, licensed CRSP inputs.",
        "The inputs remain in ignored `data/raw/`; this report contains only holding-period summaries.",
        "",
        "Window: 2023-03-13 close through 2023-12-29 close (returns begin March 14, after the main event window).",
        "Daily returns compound; the delisting-date return combines RET and DLRET. CRSP delisting code 584 with missing DLRET is treated as -100% if it occurs in-window.",
        "A severe loss is a buy-and-hold return of -50% or lower.",
        "",
        f"Universe PERMCOs: {len(results)}. Returns computed: {len(observed)}. Missing-window outcomes: {len(results) - len(observed)}.",
        f"Severe losses: {len(severe)} of {len(observed)} entities with outcomes.",
        "",
        "## Status counts",
        "",
        "| Status | Entities |",
        "|---|---:|",
    ]
    for status, count in results["oos_status"].value_counts(dropna=False).items():
        lines.append(f"| `{status}` | {count} |")
    lines += ["", "## Named cases", "", "| Ticker | PERMCO | RSSD ID | Buy-and-hold return | Status |", "|---|---:|---:|---:|---|"]
    for row in named.sort_values("ticker").itertuples(index=False):
        ret = "Missing" if pd.isna(row.oos_bhar) else f"{row.oos_bhar:.1%}"
        rssd = "" if pd.isna(row.rssd_id) else str(int(row.rssd_id))
        lines.append(f"| {row.ticker} | {row.permco} | {rssd} | {ret} | `{row.oos_status}` |")
    lines += [
        "",
        "## Interpretation limit",
        "",
        "This computes the outcome side only. The ZIP does not contain Q4 2022 FDIC measures for all 343 entities, so this report does not rank fragility scores or claim that the screen flagged any entity. First Republic and PacWest score membership remains pending the full predictor dataset.",
        "",
    ]
    OUTPUTS.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(lines), encoding="utf-8")

    print(f"Wrote {len(results)} entity-level return summaries to {OUT}")
    print(f"Wrote outcome report to {REPORT}")
    print(f"Severe losses: {len(severe)} of {len(observed)} observed entities")
    print("Named crisis securities:")
    print(named[["permco", "rssd_id", "ticker", "oos_bhar", "oos_status"]].to_string(index=False))
    if not severe.empty:
        print("\nSevere-loss cases:")
        print(severe[["permco", "ticker", "oos_bhar", "oos_status"]].sort_values("oos_bhar").to_string(index=False))
    missing = results[results["oos_bhar"].isna()]
    if not missing.empty:
        print("\nMissing outcomes:")
        print(missing[["permco", "ticker", "comnam", "oos_status"]].to_string(index=False))


if __name__ == "__main__":
    main()
